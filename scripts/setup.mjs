#!/usr/bin/env node
/**
 * One-command setup for TrustToPay.
 *
 *   1. creates .env from .env.example (with a random SESSION_SECRET)
 *   2. installs dependencies
 *   3. generates the Prisma client
 *   4. applies migrations (or db push when no migration exists)
 *   5. seeds the demo data
 *
 * No PayPal or AI credentials are required for this to work: the app starts in
 * local demo mode with clearly labelled simulated payments.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const envExamplePath = path.join(root, ".env.example");
const backendDir = path.join(root, "backend");
const migrationsDir = path.join(backendDir, "prisma", "migrations");
const dbPath = path.join(backendDir, "prisma", "dev.db");

const isWindows = process.platform === "win32";

function log(message) {
  console.log(message);
}

function run(command, args, options = {}) {
  const pretty = [command, ...args].join(" ");
  log(`\n> ${pretty}`);
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? root,
    stdio: "inherit",
    shell: isWindows,
    env: process.env,
  });
  if (result.status !== 0) {
    console.error(`\nSetup stopped: "${pretty}" failed with exit code ${result.status}.`);
    process.exit(result.status ?? 1);
  }
}

function ensureEnv() {
  if (!fs.existsSync(envExamplePath)) {
    console.error("Missing .env.example. Restore it from the repository and run setup again.");
    process.exit(1);
  }

  let contents;
  if (fs.existsSync(envPath)) {
    contents = fs.readFileSync(envPath, "utf8");
    log("Using the existing .env file.");
  } else {
    contents = fs.readFileSync(envExamplePath, "utf8");
    log("Created .env from .env.example.");
  }

  const secret = crypto.randomBytes(48).toString("hex");
  const hasSecret = /^\s*SESSION_SECRET\s*=\s*\S+/m.test(contents);
  if (!hasSecret) {
    contents = contents.replace(/^\s*SESSION_SECRET\s*=.*$/m, `SESSION_SECRET=${secret}`);
    log("Generated a random SESSION_SECRET.");
  }

  if (!/^\s*DATABASE_URL\s*=\s*\S+/m.test(contents)) {
    contents = contents.replace(
      /^\s*DATABASE_URL\s*=.*$/m,
      'DATABASE_URL="file:./dev.db"',
    );
    log('Set DATABASE_URL="file:./dev.db".');
  }

  fs.writeFileSync(envPath, contents, "utf8");
}

function main() {
  log("TrustToPay setup");
  log("===================");
  log("No credentials are required: local demo mode is the default.");
  log("");

  const major = Number(process.versions.node.split(".")[0]);
  if (!Number.isFinite(major) || major < 20) {
    console.error(`Node.js 20 or newer is required. Detected ${process.version}.`);
    process.exit(1);
  }

  ensureEnv();

  if (!fs.existsSync(path.join(root, "node_modules"))) {
    run("npm", ["install", "--no-audit", "--no-fund"]);
  }

  run("npm", ["--workspace", "backend", "run", "db:generate"]);

  const databaseExists = fs.existsSync(dbPath);
  const migrationSqlPath = path.join(migrationsDir, "0001_init", "migration.sql");

  if (fs.existsSync(migrationsDir) && !databaseExists) {
    run("npm", ["--workspace", "backend", "run", "db:migrate"]);
  } else if (!databaseExists) {
    // No migration has been checked in yet: create one, then apply it.
    const diff = spawnSync(
      "npx",
      [
        "prisma",
        "migrate",
        "diff",
        "--from-empty",
        "--to-schema-datamodel",
        "prisma/schema.prisma",
        "--script",
      ],
      { cwd: backendDir, encoding: "utf8", shell: isWindows, env: process.env },
    );
    if (diff.status === 0 && diff.stdout.trim().length > 0) {
      fs.mkdirSync(path.dirname(migrationSqlPath), { recursive: true });
      fs.writeFileSync(migrationSqlPath, diff.stdout, "utf8");
      fs.writeFileSync(
        path.join(migrationsDir, "migration_lock.toml"),
        '# Please do not edit this file manually\nprovider = "sqlite"\n',
        "utf8",
      );
      log(`\nCreated initial migration at ${path.relative(root, migrationSqlPath)}`);
      run("npm", ["--workspace", "backend", "run", "db:migrate"]);
    } else {
      run("npm", ["--workspace", "backend", "run", "db:push"]);
    }
  }

  run("npm", ["--workspace", "backend", "run", "seed"]);

  log("");
  log("Setup complete.");
  log("");
  log("Start the app with:");
  log("  npm run dev");
  log("");
  log("Then open http://localhost:5173");
  log("API docs: http://localhost:4000/api-docs");
  log("");
  log("Demo accounts (password Demo1234!):");
  log("  agent@demo.trusttopay.dev     (requester)");
  log("  reviewer@demo.trusttopay.dev  (reviewer)");
  log("  admin@demo.trusttopay.dev     (administrator)");
  log("");
  log("Payments are SIMULATED in demo mode. To make real PayPal Sandbox calls,");
  log("set DEMO_MODE=false and add PAYPAL_CLIENT_ID / PAYPAL_CLIENT_SECRET to .env.");
}

main();
